type Schema = {
  $ref?: string;
  $defs?: Record<string, Schema>;
  type?: string | string[];
  const?: unknown;
  enum?: unknown[];
  properties?: Record<string, Schema>;
  required?: string[];
  anyOf?: Schema[];
  oneOf?: Schema[];
  prefixItems?: Schema[];
  items?: Schema;
  minimum?: number;
  maximum?: number;
  minItems?: number;
  maxItems?: number;
  minLength?: number;
  maxLength?: number;
  pattern?: string;
};
const code = (value: unknown) => `\`${String(value).replaceAll("|", "\\|")}\``;
const table = (headers: string[], rows: unknown[][]) =>
  `| ${headers.join(" | ")} |\n| ${headers.map(() => "---").join(" | ")} |\n${rows.map((row) => `| ${row.map((cell) => String(cell).replaceAll("\n", " ")).join(" | ")} |`).join("\n")}\n`;
function typeOf(node: Schema, root: Schema, depth = 0): string {
  if (depth > 5) return "object";
  if (node.$ref)
    return typeOf(
      root.$defs?.[node.$ref.split("/").at(-1)!] ?? {},
      root,
      depth + 1,
    );
  if (node.const !== undefined) return code(node.const);
  if (node.enum) return node.enum.map(code).join(", ");
  if (node.anyOf || node.oneOf)
    return [
      ...new Set(
        (node.anyOf ?? node.oneOf)!.map((item) =>
          typeOf(item, root, depth + 1),
        ),
      ),
    ].join(" or ");
  if (node.prefixItems)
    return `[${node.prefixItems.map((item) => typeOf(item, root, depth + 1)).join(", ")}]`;
  return Array.isArray(node.type)
    ? node.type.join(" or ")
    : (node.type ?? "JSON");
}
function fields(schema: z.ZodType): string {
  const root = z.toJSONSchema(schema, { reused: "ref" }) as Schema;
  return table(
    ["Field", "Required", "JSON form"],
    Object.entries(root.properties ?? {}).map(([name, node]) => [
      code(name),
      root.required?.includes(name) ? "yes" : "no",
      typeOf(node, root),
    ]),
  );
}
