export async function generateCompositionReference(
  root: string,
  check = false,
): Promise<void> {
  const targets = [
    { path: "docs/composition-reference.md", text: await reference(root) },
    { path: "skills/compose-with-still-shift/SKILL.md", text: skill() },
  ];
  const stale = [];
  for (const target of targets) {
    const text = await format(target.text, { parser: "markdown" }),
      path = resolve(root, target.path);
    if (check) {
      if ((await readFile(path, "utf8").catch(() => "")) !== text)
        stale.push(target.path);
    } else {
      await mkdir(resolve(path, ".."), { recursive: true });
      await writeFile(path, text);
      console.log(`Generated ${target.path}`);
    }
  }
  if (stale.length)
    throw new Error(
      `Composition reference is stale: ${stale.join(", ")}. Run pnpm schema:generate.`,
    );
}
