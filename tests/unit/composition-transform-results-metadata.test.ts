type Work = {
  taps: number[][];
  shape?: object;
  transformProducer?: unknown;
  transforms?: number[][];
};
function owner(memory: ManagedMemory): Work | undefined {
  const resources = (
    memory as unknown as { resources: Map<object, { value: object }> }
  ).resources;
  return [...resources.values()]
    .map((x) => x.value)
    .find(
      (x) => Object.hasOwn(x, "taps") && !Object.hasOwn(x, "entryGroups"),
    ) as Work | undefined;
}
